/// `6.17.0-1018-oracle`). Unlike i686, aarch64 is a 64-bit architecture
/// like x86_64: no width mismatch with the BPF registers (always 64 bits), so standard struct
/// reflection applies directly, without the raw-offset workaround needed for i686.
