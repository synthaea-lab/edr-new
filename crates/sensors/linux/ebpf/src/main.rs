/// Ring buffer shared with userspace for `exec` events.
#[map]
static EXEC_EVENTS: RingBuf = RingBuf::with_byte_size(256 * 1024, 0);

/// Offsets of the `sched:sched_process_exec` tracepoint (x86_64). Inherited from the standard
/// layout of kernel tracepoints: an 8-byte common header (type u16, flags u8, preempt_count
/// u8, pid i32), followed by the event-specific fields. **Validated under real conditions on
/// 2026-08-12** on the WSL2 6.6.114 kernel (pid and filename readable in the produced event
/// stream).
const FILENAME_DATA_LOC_OFFSET: usize = 8;
const PID_OFFSET: usize = 12;

/// Reads `current_task->real_parent->tgid` via safe kernel reads (`bpf_probe_read_kernel`),
/// relying on the `vmlinux::task_struct` bindings generated by `aya-tool` from **this**
/// kernel's BTF. No CO-RE relocations (`bpf_core_read!`): the offsets are therefore frozen
/// for this exact kernel, which is enough for a lab agent that does not run on a
/// heterogeneous fleet of machines.
#[cfg(bpf_target_arch = "x86_64")]
fn read_ppid() -> Option<u32> {
    let task = unsafe { bpf_get_current_task() } as *const vmlinux::task_struct;
    let real_parent: *const vmlinux::task_struct = unsafe {
        bpf_probe_read_kernel(core::ptr::addr_of!((*task).real_parent) as *const _).ok()?
    };
    let ppid: i32 = unsafe {
        bpf_probe_read_kernel(core::ptr::addr_of!((*real_parent).tgid) as *const _).ok()?
    };
    Some(ppid as u32)
}

/// Reads the full arguments (`argv`) of the process being exec'd, directly from its user
/// memory: `mm->arg_start`..`mm->arg_end` covers the argv buffer (`\0`-separated strings)
/// that the kernel places on the stack at exec time. More robust than a deferred read of
/// `/proc/{pid}/cmdline` in userspace, which would lose processes too short-lived to still be
/// alive at read time — exactly the ones an attacker benefits from making ephemeral. Returns
/// `None` for kernel threads (null `mm`) or on read failure; the caller then falls back to
/// the name of the executed binary.
#[cfg(bpf_target_arch = "x86_64")]
fn read_argv(buf: &mut [u8; MAX_CMDLINE_LEN]) -> Option<u16> {
    let task = unsafe { bpf_get_current_task() } as *const vmlinux::task_struct;
    let mm: *const vmlinux::mm_struct =
        unsafe { bpf_probe_read_kernel(core::ptr::addr_of!((*task).mm) as *const _).ok()? };
    if mm.is_null() {
        return None;
    }
    let arg_start: u64 = unsafe {
        bpf_probe_read_kernel(core::ptr::addr_of!((*mm).__bindgen_anon_1.arg_start) as *const _)
            .ok()?
    };
    let arg_end: u64 = unsafe {
        bpf_probe_read_kernel(core::ptr::addr_of!((*mm).__bindgen_anon_1.arg_end) as *const _)
            .ok()?
    };
    let len = arg_end
        .saturating_sub(arg_start)
        .min(MAX_CMDLINE_LEN as u64) as usize;
    if len == 0 {
        return None;
    }
    unsafe { bpf_probe_read_user_buf(arg_start as *const u8, &mut buf[..len]).ok()? };
    Some(len as u16)
}

/// `task_struct`/`mm_struct` offsets for the i686 target (Debian 12 Bookworm, kernel
/// `6.1.0-52-686-pae`), obtained via `pahole -C task_struct`/`pahole -C mm_struct` on
/// `/usr/lib/debug/boot/vmlinux-6.1.0-52-686-pae` (package `linux-image-6.1.0-52-686-pae-dbg`,
/// `bookworm-debug` repository). **Specific to this exact kernel**, to be
/// regenerated if the kernel changes.
///
/// Raw-offset reads rather than generated struct reflection
/// (`vmlinux::task_struct`, the approach used on x86_64 above): on the
/// `bpfel-unknown-none` target, types like `c_ulong` or pointers are fixed at 8 bytes
/// regardless of the targeted host kernel's arch (the eBPF ISA uses 64-bit registers by
/// design). Reusing bindings generated by `bindgen`/`bpftool` from the i686 BTF would
/// therefore silently break the real layout of a 32-bit `task_struct`/`mm_struct` as soon as
/// it is recompiled for `bpfel-unknown-none` — confirmed by a direct test
/// (`assert!(size_of::<aya_ebpf::cty::c_ulong>() == 4)` fails to compile). Hence the explicit
/// `u32`s here, whose size depends on no compilation-target-related type resolution.
#[cfg(bpf_target_arch = "x86")]
mod i686_offsets {
    pub const TASK_MM_OFFSET: usize = 1008;
    pub const TASK_REAL_PARENT_OFFSET: usize = 1120;
    pub const TASK_TGID_OFFSET: usize = 1112;
    pub const MM_ARG_START_OFFSET: usize = 164;
    pub const MM_ARG_END_OFFSET: usize = 168;
}

#[cfg(bpf_target_arch = "x86")]
fn read_ppid() -> Option<u32> {
    use i686_offsets::{TASK_REAL_PARENT_OFFSET, TASK_TGID_OFFSET};
    let task = unsafe { bpf_get_current_task() } as usize;
    let real_parent: u32 =
        unsafe { bpf_probe_read_kernel((task + TASK_REAL_PARENT_OFFSET) as *const u32).ok()? };
    let ppid: i32 = unsafe {
        bpf_probe_read_kernel((real_parent as usize + TASK_TGID_OFFSET) as *const i32).ok()?
    };
    Some(ppid as u32)
}

#[cfg(bpf_target_arch = "x86")]
fn read_argv(buf: &mut [u8; MAX_CMDLINE_LEN]) -> Option<u16> {
    use i686_offsets::{MM_ARG_END_OFFSET, MM_ARG_START_OFFSET, TASK_MM_OFFSET};
    let task = unsafe { bpf_get_current_task() } as usize;
    let mm: u32 = unsafe { bpf_probe_read_kernel((task + TASK_MM_OFFSET) as *const u32).ok()? };
    if mm == 0 {
        return None;
    }
    let arg_start: u32 =
        unsafe { bpf_probe_read_kernel((mm as usize + MM_ARG_START_OFFSET) as *const u32).ok()? };
    let arg_end: u32 =
        unsafe { bpf_probe_read_kernel((mm as usize + MM_ARG_END_OFFSET) as *const u32).ok()? };
    let len = arg_end
        .saturating_sub(arg_start)
        .min(MAX_CMDLINE_LEN as u32) as usize;
    if len == 0 {
        return None;
    }
    unsafe { bpf_probe_read_user_buf(arg_start as *const u8, &mut buf[..len]).ok()? };
    Some(len as u16)
}

